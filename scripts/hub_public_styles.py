"""The hub's front door, dressed from the app's own token file.

WHAT THIS IS FOR. The hub is two surfaces. The operator app behind the session
gate is a Vue package that imports `web/src/styles/{tokens,theme,base}.css`
directly, so it cannot drift. The front door -- sign-in, the chooser, the domain
gallery, request-access and every refusal -- ships with no bundle on purpose
(auth pages must not depend on one loading), so it cannot import anything.

Before this, that half carried hand-copied hex values under a comment reading
"change a colour there, change its copy here", which nothing enforced. The two
halves of one property were then free to disagree about what `--surface-raised`
is, and the front door was set in the platform's font while the surface one
click further in was set in the project's.

So the values are RESOLVED out of the app's files and emitted, the way
`scripts/graph_field.py` already resolves the hub's field colours, and the four
type files are copied the way `extension/scripts/finish.mjs` copies them. Both
outputs are committed and `make lint-generated` diffs them.

    make hub-public            regenerate
    make lint-generated        fail if either output is stale

WHY NOT `emit-styles.mjs`. That script resolves every `var()` down to a literal,
because the extension paints into a page whose `:root` carries none of venona's
properties. The hub owns its own document, so it wants the opposite: the token
NAMES, declared once, with `light-dark()` intact -- which is also what lets the
rules in `pages.py` read like the app's source rather than like a palette.
"""

from __future__ import annotations

import hashlib
import re
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
TOKENS = REPO / "web" / "src" / "styles" / "tokens.css"
THEME = REPO / "web" / "src" / "styles" / "theme.css"
NODE_MODULES = REPO / "extension" / "node_modules" / "@fontsource-variable"
OUT_CSS = REPO / "hub" / "hub" / "static" / "public.css"
OUT_PY = REPO / "hub" / "hub" / "assets.py"
FONT_DIR = REPO / "hub" / "hub" / "static" / "fonts"

BANNER = (
    "/* GENERATED by scripts/hub_public_styles.py -- do not edit.\n"
    "   Source: web/src/styles/{tokens,theme}.css */\n"
)

#: The tier-2 names the front door uses. A NAMED LIST rather than the whole
#: file: this is inlined into every page the hub serves to a stranger, and the
#: entity hues, the code-highlighting ramp and the graph geometry have no reader
#: here. Every one of these is checked to exist, so a rename upstream fails the
#: build rather than resolving to nothing.
WANTED = (
    "surface-base surface-inset surface-raised surface-overlay surface-selected "
    "border-subtle border-default border-strong "
    "text-primary text-secondary text-tertiary text-quiet text-inverse text-body "
    "accent-primary accent-muted accent-wash focus-wash ring-focus "
    "signal-high signal-critical signal-ok signal-info "
    "font-ui font-mono font-prose "
    "text-2xs text-xs text-sm text-base text-md text-lg text-xl text-2xl "
    "tracking-label tracking-tight leading-tight leading-normal "
    "weight-normal weight-medium weight-semibold "
    "control-h control-h-sm control-h-touch control-h-touch "
    "radius-sm radius-md radius-lg radius-pill "
    "space-half space-1 space-2 space-3 space-4 space-5 space-6 space-7 space-8 "
    "dot-sm dot-md nav-height subnav-height page-pad measure-page field-lg "
    "motion-fast motion-base motion-ease "
    "google-button-surface google-button-ink google-button-stroke "
    "brand-wordmark brand-plate brand-monogram"
).split()

#: Declared in `theme.css` rather than `tokens.css`, and the front door needs
#: it for the width of an explanatory paragraph.
FROM_THEME = ("container-hint",)

DECL = re.compile(r"^\s*(--[a-zA-Z0-9-]+)\s*:\s*([^;]+);", re.MULTILINE)
VAR_USE = re.compile(r"var\(\s*(--[a-zA-Z0-9-]+)")


def declarations(text: str) -> dict[str, str]:
    """Every `--name: value` in declaration order; later wins, which matches
    the cascade for the single `:root` these files use."""
    return {name: value.strip() for name, value in DECL.findall(_strip_comments(text))}


def _strip_comments(css: str) -> str:
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def collect() -> list[tuple[str, str]]:
    """The wanted tokens plus, transitively, every tier-1 primitive they lean
    on -- in the order they are declared upstream, so the output reads like the
    file it came from rather than like a set."""
    tokens = declarations(TOKENS.read_text())
    tokens.update(
        {k: v for k, v in declarations(THEME.read_text()).items() if k.lstrip("-") in FROM_THEME}
    )
    order = list(tokens)

    wanted = [f"--{name}" for name in WANTED] + [f"--{name}" for name in FROM_THEME]
    missing = [name for name in wanted if name not in tokens]
    if missing:
        raise SystemExit(f"undeclared upstream: {', '.join(sorted(set(missing)))}")

    needed: set[str] = set()
    queue = list(wanted)
    while queue:
        name = queue.pop()
        if name in needed:
            continue
        needed.add(name)
        for ref in VAR_USE.findall(tokens.get(name, "")):
            if ref not in needed:
                if ref not in tokens:
                    raise SystemExit(f"{name} references undeclared {ref}")
                queue.append(ref)

    return [(name, tokens[name]) for name in order if name in needed]


def font_faces() -> tuple[str, list[tuple[Path, str]]]:
    """The four faces, and where their bytes come from.

    Latin and latin-ext for both families, which is the set
    `extension/src/shared/fonts.ts` argues for: the other six subsets per family
    are ~120kB that a page of English never fetches, and anything outside these
    ranges falls back to the platform face, which is correct rather than broken.

    The ranges and the two axes are read out of that file rather than retyped.
    JetBrains Mono is 100-800 and Inter is 100-900; they differ, and a single
    number copied to both is the kind of thing nothing would ever report.
    """
    source = (REPO / "extension" / "src" / "shared" / "fonts.ts").read_text()
    ranges = {
        key: re.search(rf"const {key} =\s*\n?\s*((?:'[^']*'\s*\+?\s*)+)", source)
        for key in ("LATIN", "LATIN_EXT")
    }
    resolved = {}
    for key, match in ranges.items():
        if match is None:
            raise SystemExit(f"{key} not found in extension/src/shared/fonts.ts")
        resolved[key] = "".join(re.findall(r"'([^']*)'", match.group(1)))

    faces = [
        ("jetbrains-mono", "jetbrains-mono-latin-wght-normal.woff2", "100 800", "LATIN"),
        ("jetbrains-mono", "jetbrains-mono-latin-ext-wght-normal.woff2", "100 800", "LATIN_EXT"),
        ("inter", "inter-latin-wght-normal.woff2", "100 900", "LATIN"),
        ("inter", "inter-latin-ext-wght-normal.woff2", "100 900", "LATIN_EXT"),
    ]
    tokens = declarations(TOKENS.read_text())
    family_of = {
        "jetbrains-mono": _primary(tokens["--font-ui"]),
        "inter": _primary(tokens["--font-prose"]),
    }

    rules = []
    copies = []
    for package, filename, weight, key in faces:
        source_file = NODE_MODULES / package / "files" / filename
        if not source_file.is_file():
            raise SystemExit(f"missing {source_file} -- run `cd extension && npm install`")
        copies.append((source_file, filename))
        rules.append(
            "@font-face {\n"
            f"  font-family: '{family_of[package]}';\n"
            "  font-style: normal;\n"
            "  font-display: swap;\n"
            f"  font-weight: {weight};\n"
            f"  src: url('/fonts/{filename}') format('woff2-variations');\n"
            f"  unicode-range: {resolved[key]};\n"
            "}"
        )
    return "\n".join(rules), copies


def _primary(stack: str) -> str:
    """The family a token's stack asks for FIRST, unquoted.

    Derived rather than written down. A name typed here would be a second copy
    of what `tokens.css` already says, which is exactly how `Inter var` and
    `Charter` survived in the app: the stack said one thing, what shipped said
    another, and nothing compared them.
    """
    return stack.split(",")[0].strip().strip("'\"")


#: The hand-written half. Kept as a real stylesheet rather than as a Python
#: string, which is the whole reason `lint_tokens.py` can see it at all.
RULES = REPO / "hub" / "hub" / "styles" / "public.css"


def build() -> tuple[str, list[tuple[Path, str]]]:
    """The served sheet: the faces, the tokens they need, then the rules.

    In that order, and it matters. `@font-face` first so the browser has the
    families before anything asks for one; the token block next, because every
    rule below reads from it; the hand-written rules last, so a declaration
    there wins over the block it is written against.
    """
    faces, copies = font_faces()
    body = "\n".join(f"  {name}: {value};" for name, value in collect())
    rules = RULES.read_text()
    css = f"{BANNER}{faces}\n\n:root {{\n{body}\n}}\n\n{rules}"
    return css, copies


def main(check: bool) -> int:
    css, copies = build()
    digest = hashlib.sha256(css.encode()).hexdigest()[:12]
    module = (
        '"""GENERATED by scripts/hub_public_styles.py -- do not edit.\n\n'
        "The front door's stylesheet, at a URL naming its own contents so it can\n"
        'be cached for a year on a service whose every page is `no-store`.\n"""\n\n'
        "from __future__ import annotations\n\n"
        f'PUBLIC_CSS_URL = "/public.{digest}.css"\n\n'
        "#: Served from `/fonts/<name>`, spelled once so `routers/brand.py` and\n"
        "#: the stylesheet above cannot disagree about a filename.\n"
        "FONT_FILES = (\n" + "".join(f'    "{name}",\n' for _, name in copies) + ")\n"
    )

    if check:
        stale = []
        if not OUT_CSS.is_file() or OUT_CSS.read_text() != css:
            stale.append(OUT_CSS)
        if not OUT_PY.is_file() or OUT_PY.read_text() != module:
            stale.append(OUT_PY)
        for source, name in copies:
            target = FONT_DIR / name
            if not target.is_file() or target.read_bytes() != source.read_bytes():
                stale.append(target)
        for path in stale:
            print(f"stale: {path.relative_to(REPO)}")
        return 1 if stale else 0

    FONT_DIR.mkdir(parents=True, exist_ok=True)
    OUT_CSS.write_text(css)
    OUT_PY.write_text(module)
    for source, name in copies:
        shutil.copyfile(source, FONT_DIR / name)
        # A woff2 begins `wOF2`. Same reasoning as the extension's check: a
        # truncated or wrong file renders in the platform face, which looks
        # like a design choice rather than like a failure.
        head = (FONT_DIR / name).read_bytes()[:4]
        if head != b"wOF2":
            raise SystemExit(f"{name} is not a woff2 ({head!r})")
    print(
        f"hub public styles -> {OUT_CSS.relative_to(REPO)} ({len(css)} bytes, {len(copies)} faces)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main("--check" in sys.argv))
