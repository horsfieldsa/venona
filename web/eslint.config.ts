import pluginVue from 'eslint-plugin-vue'
import { defineConfigWithVueTs, vueTsConfigs } from '@vue/eslint-config-typescript'
import importX from 'eslint-plugin-import-x'

/**
 * The rules that catch what `vue-tsc` cannot.
 *
 * `tsconfig.json` is already strict (`noUnusedLocals`, `noUnusedParameters`,
 * `noFallthroughCasesInSwitch`, `verbatimModuleSyntax`) and the codebase is
 * already clean -- 65 of 65 SFCs on `<script setup lang="ts">`, every
 * `defineProps` type-generic, every `$emit` declared, no props destructuring, no
 * `reactive` misuse. So this is deliberately NOT a style pass. Every rule below
 * either maps to a defect class the typechecker is structurally blind to, or to
 * a rule this codebase already states in prose and had no way to enforce.
 *
 * CATEGORY A ONLY (`flat/essential`), and that is a correction to the first
 * attempt at this config.
 *
 * The plan said A+B. Measured, B is overwhelmingly FORMATTING --
 * `max-attributes-per-line`, `singleline-html-element-content-newline`,
 * `html-indent` -- and it produced 1,042 warnings across the tree, none of them
 * a defect. That is a whole-tree reformat wearing a lint config, which is the
 * precise thing this file declines Prettier for two paragraphs down. Taking it
 * would have been incoherent.
 *
 * Category A is the tier whose members are bugs rather than preferences. The
 * rules worth having from further up are enabled by hand below, with the reason
 * each one earns its place.
 *
 * WHY `@vue/eslint-config-typescript` RATHER THAN ASSEMBLING THE PARSERS. The
 * fiddly part of this stack is type-aware linting INSIDE a `<script setup>`
 * block: `vue-eslint-parser` on top, `@typescript-eslint/parser` underneath it,
 * `extraFileExtensions`, and `projectService` all having to agree. That package
 * exists to get exactly that right and pins the three pieces that must match.
 *
 * NO PRETTIER, and the reasoning is in the plan: `src/api/schema.d.ts` is 7,136
 * generated lines that `make lint-generated` diffs byte for byte, so a formatter
 * would need a permanent exemption for the one file most likely to be reformatted
 * -- and the drift a formatter prevents is a multi-contributor problem this
 * single-machine project does not have.
 */
export default defineConfigWithVueTs(
  {
    name: 'venona/ignores',
    ignores: [
      'dist/**',
      'node_modules/**',
      'public/**',
      // NON-NEGOTIABLE. Generated by `make types`, committed, and diffed byte
      // for byte by `make lint-generated`. Any autofix that touches it puts
      // `make lint` permanently at war with `make types`.
      'src/api/schema.d.ts',
    ],
  },

  pluginVue.configs['flat/essential'],
  vueTsConfigs.recommendedTypeChecked,

  {
    name: 'venona/rules',
    plugins: { 'import-x': importX },
    rules: {
      // ── what vue-tsc cannot see ────────────────────────────────────────
      /**
       * The highest-value rule here, and it is in no preset.
       *
       * 27 `ref="..."` template refs and zero `useTemplateRef`, so every one is
       * matched to a `const x = ref(null)` by NAME. Rename the script side and
       * forget the template and you get a silent `null` at runtime that
       * typechecks perfectly.
       */
      'vue/no-unused-refs': 'error',

      /**
       * Zero usages today, and three files -- `GuideView`, `BriefBlock`,
       * `GuideRuns` -- carry comments stating "NO v-html" as a design rule.
       * Free, and it turns a prose invariant into a tool.
       */
      'vue/no-v-html': 'error',

      // ── promises ──────────────────────────────────────────────────────
      /**
       * `ignoreVoid` is the default. Set EXPLICITLY, with this comment, because
       * the codebase leans on `void expr` as its deliberate fire-and-forget
       * idiom in ~87 places (`void start()`, `void runTypes.load()`), and the
       * next person to see one should find the reason here rather than delete
       * the `void` to "clean it up".
       */
      '@typescript-eslint/no-floating-promises': ['error', { ignoreVoid: true }],

      /**
       * `attributes: false` or every `@click="async () => …"` fires -- there are
       * 14 async handlers in templates and they are all correct. The cases worth
       * catching are an async function passed where a sync predicate is
       * expected, which this still reports.
       */
      '@typescript-eslint/no-misused-promises': [
        'error',
        { checksVoidReturn: { attributes: false } },
      ],

      // ── imports ───────────────────────────────────────────────────────
      /**
       * GROUPS ONLY. No `alphabetize`.
       *
       * The existing convention is real -- external packages, blank line, `@/`
       * internals -- but WITHIN the internal group it is not alphabetical, and
       * turning that on would rewrite the import block of ~74 files to catch
       * nothing. That is the same unreviewable-autofix-diff this config declines
       * Prettier for, in a smaller costume.
       */
      'import-x/order': [
        'error',
        {
          groups: [['builtin', 'external'], 'internal', ['parent', 'sibling', 'index']],
          'newlines-between': 'always',
        },
      ],

      // ── noise floor ───────────────────────────────────────────────────
      'no-console': ['error', { allow: ['warn', 'error'] }],

      // ── turned OFF, with the reason ───────────────────────────────────
      /**
       * Category A, so on by default, and it fires on ELEVEN files: `Button`,
       * `Chip`, `Dialog`, `Icon`, `Kbd`, `Panel`, `Spinner`, `Table`, `Toggle`,
       * `Wordmark`, `Bracket`. Those names are deliberate -- CLAUDE.md's "never
       * add a second implementation of a `components/ui/` primitive" only means
       * anything if each primitive has one canonical short name.
       */
      'vue/multi-word-component-names': 'off',

      /**
       * WARN, not error, and not yet triaged. Very noisy over optional chains on
       * generated API types, which mark a great deal optional -- and some of
       * those chains ARE dead defensive branches worth deleting. Promote once
       * the count is worked through; the count is in the commit message.
       */
      '@typescript-eslint/no-unnecessary-condition': 'warn',

      /**
       * OFF, and this one is a false positive rather than a judgement call.
       *
       * `InstanceType<typeof SomeSFC>` resolves to `any` for a Vue SFC, so
       * `ref<InstanceType<typeof ViewShell> | null>(null)` -- the standard way to
       * type a component template ref, used exactly as the Vue docs show it --
       * reads to this rule as "`any` overrides all other types in this union".
       * The alternative is dropping the `| null`, which is worse: the ref really
       * is null before mount.
       */
      '@typescript-eslint/no-redundant-type-constituents': 'off',
    },
  },

  {
    // Specs reach for `any` and stub globals; that is what a test double is.
    name: 'venona/tests',
    files: ['**/*.spec.ts'],
    rules: {
      '@typescript-eslint/no-explicit-any': 'off',
      '@typescript-eslint/no-unsafe-assignment': 'off',
      '@typescript-eslint/no-unsafe-member-access': 'off',
      '@typescript-eslint/no-unsafe-argument': 'off',
      '@typescript-eslint/no-unsafe-call': 'off',
      /**
       * A `fetch` double is `vi.fn(async (input) => new Response(...))` and has
       * nothing to await -- it is async because the thing it replaces is. Adding
       * a pointless `await` to satisfy this would make the mocks lie about their
       * timing, which is exactly what `briefs.spec.ts`'s out-of-order tests
       * depend on being able to control.
       */
      '@typescript-eslint/require-await': 'off',
    },
  },
)
