import { fileURLToPath, URL } from 'node:url'
import tailwindcss from '@tailwindcss/vite'
import vue from '@vitejs/plugin-vue'
import { defineConfig } from 'vite'

/** The content script is built alone, as an IIFE.
 *
 * A content script cannot be an ES module -- Chrome loads it as a classic
 * script -- so `import()` inside it is unavailable and every dependency must be
 * in the one file. That is why the hover card's Vue runtime is bundled here
 * eagerly rather than lazy-loaded: a dynamic chunk would need
 * `web_accessible_resources` plus `chrome.runtime.getURL`, which is a different
 * and larger design.
 *
 * Rollup emits IIFE for a single entry only, which is the whole reason this is
 * a separate config from `vite.main.config.ts`.
 */
export default defineConfig({
  plugins: [vue(), tailwindcss()],
  resolve: {
    // `@` matches the app's own alias, so `EntityCardBody.vue` and its imports
    // resolve unchanged. That is what lets the card be the SAME component
    // rather than a copy that drifts.
    alias: {
      '@': fileURLToPath(new URL('../web/src', import.meta.url)),
      '@web': fileURLToPath(new URL('../web/src', import.meta.url)),
    },
  },
  build: {
    outDir: 'dist',
    emptyOutDir: true,
    // Pinned to `light-dark()`'s own baseline, and it must stay in step with
    // `web/vite.config.ts` -- that file carries the reasoning, and
    // `tests/test_css_target.py` fails if the two drift. Without it Lightning
    // CSS polyfills `light-dark()` on build and leaves it alone in dev, so the
    // shadow root's tokens would answer to a build-time snapshot of
    // `color-scheme` rather than to the runtime cascade.
    cssTarget: ['chrome123', 'safari17.5', 'firefox120'],
    // The page stylesheet is generated by `scripts/emit-styles.mjs` and listed
    // in the manifest, not imported here -- it belongs to the PAGE, not to the
    // shadow root, and must load before the script runs.
    cssCodeSplit: false,
    rollupOptions: {
      input: fileURLToPath(new URL('./src/content/index.ts', import.meta.url)),
      output: {
        format: 'iife',
        entryFileNames: 'content.js',
        assetFileNames: 'content-[name][extname]',
        inlineDynamicImports: true,
      },
    },
  },
})
