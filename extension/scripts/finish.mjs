/** Copy what the browser loads by name, then check the build is not hollow.
 *
 * `mentions.css` is named by `chrome.scripting.registerContentScripts` in
 * `background.ts`, so Chrome fetches it from the extension root. No module
 * imports it, so Vite never sees it and it has to be copied.
 *
 * The `icons/` copy is the other one: `manifest.json` names four PNGs and
 * nothing imports them either. A missing 128px icon is a Web Store rejection
 * and a grey puzzle piece in the toolbar, neither of which the bundle notices.
 *
 * The assertions matter more than the copy. The card's utility classes are
 * generated by Tailwind from `web/src/components/**`, which lives outside this
 * Vite root and is therefore reachable only through the explicit `@source`
 * directives in `card.css` -- the one place this project uses them, against the
 * advice in `theme.css`. When an `@source` silently stops matching, Tailwind
 * does not fail: it emits a stylesheet with the rules missing, and the card
 * renders as unstyled text in a box. `theme.css` records that exact failure
 * happening once already, in the app, where it cost a header its gutter.
 *
 * So: name a class from each layer and refuse to ship a bundle without them.
 */

import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { fileURLToPath, URL } from 'node:url'
import { stripCssComments } from '../../tooling/vite-strip-comments.mjs'

const here = (p) => fileURLToPath(new URL(p, import.meta.url))

const ICON_SIZES = [16, 32, 48, 128]

/** The typefaces, and the third thing nothing imports.
 *
 * `src/shared/fonts.ts` builds `@font-face` rules at runtime with
 * `chrome.runtime.getURL('fonts/<file>')` -- it cannot `import` the woff2,
 * because a content script's shadow root needs an absolute
 * `chrome-extension://` URL and a bundled asset reference would resolve against
 * the HOST page. So Vite never sees these files and they are copied, exactly
 * like `mentions.css` and the icons.
 *
 * Latin and latin-ext only; `fonts.ts` says why. THREE PLACES have to agree on
 * these names -- here, `FACES` in `fonts.ts`, and `web_accessible_resources` in
 * `manifest.json` -- and the failure when they do not is a card that renders in
 * the platform's mono, which looks like a design choice. The assertion at the
 * bottom of this file is what catches it.
 */
const FONT_FILES = [
  'jetbrains-mono-latin-wght-normal.woff2',
  'jetbrains-mono-latin-ext-wght-normal.woff2',
  'inter-latin-wght-normal.woff2',
  'inter-latin-ext-wght-normal.woff2',
]

const fontSource = (file) =>
  here(`../node_modules/@fontsource-variable/${file.startsWith('inter-') ? 'inter' : 'jetbrains-mono'}/files/${file}`)

await mkdir(here('../dist/icons'), { recursive: true })
await mkdir(here('../dist/fonts'), { recursive: true })

for (const [from, to] of [
  ['../manifest.json', '../dist/manifest.json'],
  ...ICON_SIZES.map((size) => [`../icons/venona-${size}.png`, `../dist/icons/venona-${size}.png`]),
]) {
  await copyFile(here(from), here(to))
  console.log(`${from.replace('../', '')} -> ${to.replace('../', '')}`)
}

// The channel, stamped where scripts can see it. A store build defaults every
// request at production, so a stale store `dist/` under ext-smoke would drive
// the harness against the live corpus -- `ext_smoke.py` refuses on this file.
// Removed (not skipped) on dev builds so the marker cannot outlive its build.
//
// The store manifest also sheds its localhost grants: `http://127.0.0.1:*` in
// `host_permissions` is a review question and a pointless install-time ask for
// a store user, so both move to OPTIONAL -- a store install can still opt into
// a local dev API from the options page, it just prompts. The theme bridge
// likewise stops matching the Vite proxy. The DEV manifest is untouched,
// `key` included: ext-smoke asserts the pinned id, and the id is how a dev
// profile keeps its storage across rebuilds.
{
  const channel = process.env.VITE_EXT_CHANNEL === 'store' ? 'store' : 'dev'
  if (channel === 'store') {
    const manifest = JSON.parse(await readFile(here('../dist/manifest.json'), 'utf8'))
    const isLocal = (pattern) => pattern.startsWith('http://127.0.0.1:')
    const shed = manifest.host_permissions.filter(isLocal)
    manifest.host_permissions = manifest.host_permissions.filter((p) => !isLocal(p))
    manifest.optional_host_permissions = [...manifest.optional_host_permissions, ...shed]
    for (const script of manifest.content_scripts) {
      script.matches = script.matches.filter((p) => !isLocal(p))
    }
    await writeFile(here('../dist/manifest.json'), JSON.stringify(manifest, null, 2) + '\n')
    await writeFile(here('../dist/CHANNEL'), 'store\n')
    console.log('dist/CHANNEL -> store (localhost grants moved to optional)')
  } else {
    await rm(here('../dist/CHANNEL'), { force: true })
  }
}

// Stripped rather than copied. This is the one stylesheet that reaches a reader
// without passing a bundler, and `background.ts` injects it into every page they
// visit -- so its comments, and the source paths they name, would be readable in
// devtools on any site. `generated/` keeps them for whoever is debugging the
// emitter.
{
  const css = await readFile(here('../generated/mentions.css'), 'utf8')
  await writeFile(here('../dist/mentions.css'), stripCssComments(css))
  console.log('generated/mentions.css -> dist/mentions.css (comments stripped)')
}

for (const file of FONT_FILES) {
  await copyFile(fontSource(file), here(`../dist/fonts/${file}`))
  console.log(`node_modules/@fontsource-variable/… -> dist/fonts/${file}`)
}

// A woff2 begins `wOF2`. Same reasoning as the PNG signature below: the failure
// that actually happens is a truncated or wrong-named file arriving with a
// successful exit code, and a zero-byte font is indistinguishable at runtime
// from a font that was never declared -- the card just renders in the fallback.
for (const file of FONT_FILES) {
  const bytes = await readFile(here(`../dist/fonts/${file}`))
  if (bytes.subarray(0, 4).toString('latin1') !== 'wOF2') {
    console.error(`\nfonts/${file} is not a woff2 (${bytes.length} bytes)`)
    console.error('reinstall with `cd extension && npm ci`')
    process.exit(1)
  }
}

// A PNG's first eight bytes are a fixed signature. Checking it rather than
// existence catches the failure that actually happens: `rsvg-convert` writing a
// zero-byte or truncated file and exiting 0, which `make icons` would not
// notice and the toolbar would render as nothing at all.
for (const size of ICON_SIZES) {
  const bytes = await readFile(here(`../dist/icons/venona-${size}.png`))
  const signature = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])
  if (!bytes.subarray(0, 8).equals(signature)) {
    console.error(`\nicons/venona-${size}.png is not a PNG (${bytes.length} bytes)`)
    console.error('regenerate with `make icons`')
    process.exit(1)
  }
}

const bundle = await readFile(here('../dist/content.js'), 'utf8')

const required = {
  // GENERATED RULES, not bare class names.
  //
  // What this checks is that the card body and the ui primitives arrive with
  // their utilities -- the failure being a card that mounts and renders
  // unstyled, which reads on the page as "the extension is broken" with nothing
  // in the console.
  //
  // Two earlier versions of this check did not do that. `bg-surface-overlay`
  // appears zero times in EntityCardBody.vue and twice in the extension's own
  // HoverCard.vue, so it was satisfied by the wrong file entirely. Replacing it
  // with a class only EntityCardBody.vue uses was still not enough, because
  // HoverCard.vue IMPORTS that component: every class in its template lands in
  // the compiled JS whether or not Tailwind emitted a rule for it. Only the
  // `.class{` form distinguishes "the name is in the bundle" from "the bundle
  // can style it".
  //
  // Note this does NOT prove the `@source` lines in card.css are live --
  // Tailwind v4's Vite plugin already scans the import graph, so anything the
  // card actually renders is picked up either way. Those globs cover files
  // reached only at runtime; removing one costs ~3.5 kB of rules for entity
  // components the extension does not mount.
  'rule from the app component': '.border-l-accent-muted{',
  'rule from a ui primitive': '.text-text-primary{',
  // Proof the generated :host block was inlined AND resolved to literals --
  // `var(--aqua-600)` surviving here would mean the card renders colourless.
  //
  // `--accent-muted`, NOT an entity colour. The entity family is
  // ontology-derived and keeps moving, so naming one here makes this fail on a
  // token's ABSENCE while claiming the bundle is hollow -- `make ext-build` red
  // with a diagnosis pointing at the wrong thing entirely. `lint_tokens.py`
  // already guards that family. All this line needs to prove is that `var()`
  // got resolved, and a tier-2 token nothing generates proves it stably.
  //
  // It is `light-dark(` rather than a hex, and that is a STRONGER assertion than
  // the one it replaces, not a weakening. `--accent-muted:#1891ac` proved that
  // `var()` resolved. This proves that AND that both palettes made it through
  // `emit-styles.mjs` intact -- the flattening it does for `mentions.css` must
  // NOT happen here, because the card is a shadow root the extension owns and
  // therefore themes through `color-scheme`.
  ':host tier-2 token, resolved, both palettes': '--accent-muted:light-dark(',
  // Tier-1 primitives never carry `light-dark()` -- they are raw values, and the
  // pairing happens one tier up. This needle proves that too, now: if the light
  // palette ever leaked into tier 1 this stops matching.
  ':host tier-1 token': '--aqua-600:#1891ac',
  // The switch itself. Without a `color-scheme` inside the shadow root every
  // `light-dark()` above resolves to its LIGHT side -- `card.css` opens with
  // `:host { all: initial }`, whose initial value for `color-scheme` is
  // `normal`, and `normal` means light. Every token present, every one wrong.
  'the shadow root declares a color-scheme': 'color-scheme:light dark',
  // Proof the mention classes the splicer writes are the ones the page styles.
  'mention class in the splicer': 'venona-mention--',
  // A CANARY for the `components/brand` @source glob, which is a third source
  // root outside this Vite project and is reached only through the explicit
  // `@source` line in `card.css`.
  //
  // WHY THIS CLASS. The card renders `Mark.vue`, so nothing on this surface
  // paints with `w-auto` -- it is on the inlined lockup `<svg>` in
  // `Wordmark.vue`, which the extension does not import at all. Tailwind scans
  // source TEXT, not the module graph, so the glob emits it anyway, and that is
  // precisely what makes it a probe: it is the only class the brand directory
  // uniquely produces, so its absence is the only thing that proves the glob
  // stopped matching. The mark's own utilities (`rounded-md`, `flex-none`,
  // `block`) are emitted by other files regardless and could tell you nothing.
  //
  // NOT `.text-brand-wordmark{`: the inlined lockup sets `color` with that
  // class, and it names a token the card's own `:host` block also carries, so
  // it proves nothing. `w-auto` appears in exactly two files in the whole repo,
  // `Wordmark.vue` and `brief/BriefItem.vue`, and `brief/` is not one of
  // `card.css`'s @source roots. If it ever appears in `components/ui`,
  // `components/entity` or `content/`, this stops being a probe and needs
  // moving again.
  'rule from the brand lockup': '.w-auto{',
  // And the mark itself, INLINED. `venona-mark-aqua.svg` is 499 bytes, under
  // Vite's 4096-byte `assetsInlineLimit`, so it must land as a data URI. If it
  // ever grows past that limit Vite emits a FILE reference instead -- which a
  // content script resolves against the HOST page's origin, giving a broken image
  // on every real site while the local fixture still looks fine.
  'the mark, inlined rather than emitted as a file': 'data:image/svg+xml',
  // The typefaces reach the card only if `installFonts` survived tree-shaking
  // and the filenames still match what was copied above. A card whose fonts
  // failed to load does not error -- it renders in the platform's mono, which
  // is what it did for the whole life of the extension before this check.
  'the font installer, in the content bundle': 'jetbrains-mono-latin-wght-normal.woff2',
  'the prose face too, not just the chrome one': 'inter-latin-wght-normal.woff2',
}

const missing = Object.entries(required).filter(([, needle]) => !bundle.includes(needle))
if (missing.length) {
  console.error('\nthe content bundle is missing things it cannot work without:')
  for (const [label, needle] of missing) console.error(`  ${label}: expected ${JSON.stringify(needle)}`)
  process.exit(1)
}

console.log(`content bundle ok (${Object.keys(required).length} assertions, ${bundle.length} bytes)`)

// The third corner of the triangle. `fonts.ts` asks for these by name and this
// script copies them, but a content script may only fetch a path the manifest
// declares web-accessible -- otherwise `chrome.runtime.getURL` returns a URL
// that is blocked on every host page, with the failure visible only as the
// wrong typeface.
const manifest = JSON.parse(await readFile(here('../dist/manifest.json'), 'utf8'))
const exposed = (manifest.web_accessible_resources ?? []).flatMap((entry) => entry.resources ?? [])
const unexposed = FONT_FILES.filter(
  (file) => !exposed.includes(`fonts/${file}`) && !exposed.includes('fonts/*.woff2'),
)
if (unexposed.length) {
  console.error('\nfonts are in the bundle but not web-accessible:')
  for (const file of unexposed) console.error(`  fonts/${file}`)
  console.error('add them to `web_accessible_resources` in manifest.json')
  process.exit(1)
}

console.log(`fonts ok (${FONT_FILES.length} faces, copied and web-accessible)`)

// ── the theme-sync script, and what it must NOT be ──────────────────
//
// `theme.js` is a second content script, registered STATICALLY against venona's
// own origins -- the one place `shared/sites.ts` deliberately refuses to
// register the splicer, because deriving that registration from
// `permissions.getAll().origins` would inject `content.js` into the app itself.
// That reason has not changed, so the two must not converge.
//
// Its whole job is to copy the app's theme choice into `chrome.storage.sync`,
// because the service worker that paints the badge has no DOM and no
// `matchMedia` and cannot resolve `light-dark()` for itself.
//
// The size bound is the real check. A bundle that grew past a few kB is one that
// started importing the card, the splicer or Vue, and the failure would be
// venona's own app being annotated by its own extension -- which looks, at
// first, like a feature.
const themeScript = await readFile(here('../dist/theme.js'), 'utf8')
//
// The needles have to be chosen against each other, not just against the source.
// `'theme'` alone is a substring of `data-theme`, so a pair of checks like that
// is satisfied by one token and proves nothing.
const themeChecks = {
  'reads the attribute the app resolves its palette from': 'data-theme',
  'writes through chrome.storage.sync': 'chrome.storage.sync.set',
  'observes the attribute rather than polling': 'MutationObserver',
}
const themeMissing = Object.entries(themeChecks).filter(([, needle]) => !themeScript.includes(needle))
// `localStorage` and the app's storage key: this script reads the ATTRIBUTE, and
// a copy of that key here is a second holder of a string it cannot import
// (docs/adr/0177). The splicer needles are the size bound's companions.
const forbidden = [
  'venona-mention',
  'attachShadow',
  'venona-card-host',
  'localStorage',
  'venona.theme',
].filter((needle) => themeScript.includes(needle))
if (themeMissing.length || forbidden.length || themeScript.length > 4096) {
  console.error('\ndist/theme.js is not what it has to be:')
  for (const [label, needle] of themeMissing) {
    console.error(`  missing ${label}: expected ${JSON.stringify(needle)}`)
  }
  for (const needle of forbidden) {
    console.error(`  contains ${JSON.stringify(needle)} -- this runs on venona's OWN origin, reads`)
    console.error(`  the attribute and nothing else, and must never carry the splicer or the card`)
  }
  if (themeScript.length > 4096) {
    console.error(`  ${themeScript.length} bytes, over the 4096 bound -- it has grown a dependency`)
  }
  process.exit(1)
}

const registered = (manifest.content_scripts ?? []).flatMap((entry) => entry.js ?? [])
if (!registered.includes('theme.js')) {
  console.error('\ndist/theme.js is built but no `content_scripts` entry names it')
  console.error('without that, the badge never learns which theme the reader chose')
  process.exit(1)
}

console.log(`theme sync ok (${themeScript.length} bytes, own-origin only)`)
