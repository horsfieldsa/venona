from __future__ import annotations

from pathlib import Path

from alembic import op

revision = "0001_baseline"
down_revision = None
branch_labels = None
depends_on = None

#: The `.sql` files, in order. THEY are the DDL, not this file.
#:
#: This revision executes them rather than restating them as `op.create_table`
#: calls, and that is the whole design: those files carry the reasoning -- why
#: `mcp_tokens.token_hash` is a bare SHA-256 rather than a KDF, why `aliases` is
#: keyed on the surface and not the normalised form, why `brief_items.ord` had to
#: exist at all -- and an autogenerated `op.create_table` carries a column list.
#:
#: What Alembic adds is versioning, ordering and a downgrade path. It does not
#: need to own the SQL to do any of that.
SQL_DIR = Path(__file__).resolve().parents[2] / "migrations"
FILES = ("0001_baseline.sql", "0002_identity.sql", "0003_oauth.sql")


def upgrade() -> None:
    # ALREADY-MIGRATED DATABASES ARE THE INTERESTING CASE. Every existing
    # instance ran these through the old `schema_migrations` ledger, so replaying
    # them would fail on the first `CREATE TABLE`. If that ledger says a file has
    # run, this revision has nothing to do for it -- it is being stamped, not
    # applied.
    connection = op.get_bind()
    applied: set[str] = set()
    exists = connection.exec_driver_sql(
        "SELECT 1 FROM information_schema.tables "
        "WHERE table_schema = 'public' AND table_name = 'schema_migrations'"
    ).fetchone()
    if exists:
        applied = {
            row[0] for row in connection.exec_driver_sql("SELECT name FROM schema_migrations")
        }

    for name in FILES:
        if name in applied:
            continue
        connection.exec_driver_sql((SQL_DIR / name).read_text())


def downgrade() -> None:
    # `DROP SCHEMA public CASCADE` and no less, because the baseline IS the
    # schema: there is no earlier state to return to, and a downgrade that
    # dropped 29 tables one at a time would differ from this only in how many
    # ways it could be wrong.
    #
    # Deliberately destructive and deliberately explicit. Nothing calls it; it
    # exists so `alembic downgrade base` means something rather than silently
    # doing nothing, which is the failure mode of a `pass` here.
    op.execute("DROP SCHEMA public CASCADE")
    op.execute("CREATE SCHEMA public")
